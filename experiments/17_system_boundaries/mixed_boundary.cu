#include <cuda_runtime.h>
#include <stdio.h>
#include <stdlib.h>

__device__ __forceinline__ unsigned int core_clock() {
  unsigned int value;
  asm volatile("mov.u32 %0, %%clock;" : "=r"(value));
  return value;
}

// Fixed launch geometry across all pressures. Writer cohorts issue complete
// pages; cohort spacing changes arrival burstiness, never page byte coverage.
__global__ void mixed_boundary(unsigned long long base, unsigned int *out,
                               int write_pages, unsigned long long gap_cycles,
                               int permutation, unsigned int read_delay) {
  int lane = threadIdx.x % 32;
  if (blockIdx.x == 0) {
    int warp = threadIdx.x / 32;
    if (warp >= 16) return;
    unsigned int read_start = core_clock();
    while ((unsigned int)(core_clock() - read_start) < read_delay) { }
    unsigned int sum = 0;
    for (int iteration = 0; iteration < 8; ++iteration) {
      unsigned long long page = (warp + iteration * 16 + permutation) % 128;
      volatile unsigned int *src = (volatile unsigned int *)(
          base + page * 4096ULL + lane * 4ULL);
      sum += src[0];
    }
    if (lane == 0) out[warp] = sum;
  } else {
    int page = blockIdx.x - 1;
    if (page >= write_pages) return;
    // All 4096 bytes are generated by one resident CTA. No page spans CTAs
    // that may be admitted at different times by the GPU scheduler.
    unsigned int start = core_clock();
    unsigned long long delay = (unsigned long long)page * gap_cycles;
    while ((unsigned int)(core_clock() - start) < delay) { }
    int physical_page = (page + permutation) % write_pages;
    volatile unsigned int *dst = (volatile unsigned int *)(
        base + (1ULL << 30) + physical_page * 4096ULL + threadIdx.x * 4ULL);
    dst[0] = (unsigned int)(page * 1024 + threadIdx.x);
  }
}

int main(int argc, char **argv) {
  int pages = argc > 1 ? atoi(argv[1]) : 4;
  unsigned long long gap = argc > 2 ? strtoull(argv[2], NULL, 0) : 0;
  int permutation = argc > 3 ? atoi(argv[3]) : 0;
  unsigned long long base = argc > 4 ? strtoull(argv[4], NULL, 0) : 274877906944ULL;
  unsigned int read_delay = argc > 5 ? (unsigned int)strtoul(argv[5], NULL, 0) : 0;
  if (pages < 0 || pages > 16 || permutation < 0 || permutation > 127) return 2;
  unsigned int *out = NULL;
  cudaError_t status = cudaMalloc(&out, 16 * sizeof(*out));
  if (status != cudaSuccess) return 1;
  // One reader CTA and 16 writer CTAs; each writer owns a full 4 KiB page.
  mixed_boundary<<<17, 1024>>>(base, out, pages, gap, permutation, read_delay);
  status = cudaDeviceSynchronize();
  if (status != cudaSuccess) {
    fprintf(stderr, "mixed boundary failed: %s\n", cudaGetErrorString(status));
    return 1;
  }
  cudaFree(out);
  printf("[MIXED-BOUNDARY] pages=%d gap=%llu permutation=%d\n", pages, gap, permutation);
  return 0;
}
